#!/usr/bin/env bash
# Render THIRD_PARTY_LICENSES.md from build/versions.env + build/licenses/components.tsv.
#
#   build/third-party-licenses.sh                  # (re)write THIRD_PARTY_LICENSES.md at the repo root
#   build/third-party-licenses.sh --check          # fail if the committed file is stale
#   build/third-party-licenses.sh --release-notes  # print the "Third-party licenses" section for release notes
#   OUT=/path/file.md build/third-party-licenses.sh
#
# Fails when a <NAME>_VERSION in versions.env has no row in components.tsv (and vice versa), so a new
# dependency cannot ship unattributed. Output is deterministic (no timestamps; row order = TSV order).
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
root="$(cd "$here/.." && pwd)"
versions="$here/versions.env"
tsv="$here/licenses/components.tsv"
out="${OUT:-$root/THIRD_PARTY_LICENSES.md}"
mode="${1:-write}"

die() { printf 'third-party-licenses: %s\n' "$*" >&2; exit 1; }
[[ -f "$versions" ]] || die "missing $versions"
[[ -f "$tsv" ]] || die "missing $tsv"

# shellcheck source=/dev/null
source "$versions"

pinned=$(grep -E '^[A-Z0-9_]+_VERSION=' "$versions" | cut -d= -f1 | sort)
listed=$(grep -vE '^(#|$)' "$tsv" | cut -f1 | sort)
dupes=$(printf '%s\n' "$listed" | uniq -d)
[[ -z "$dupes" ]] || die "duplicate rows in components.tsv: $(echo $dupes)"
missing=$(comm -23 <(printf '%s\n' "$pinned") <(printf '%s\n' "$listed"))
[[ -z "$missing" ]] || die "no license row in build/licenses/components.tsv for: $(echo $missing)"
extra=$(comm -13 <(printf '%s\n' "$pinned") <(printf '%s\n' "$listed"))
[[ -z "$extra" ]] || die "components.tsv rows without a pin in versions.env: $(echo $extra)"

# rows: var name spdx lname lurl source copyleft dist note  (expanded)
rows=()
while IFS=$'\t' read -r var name spdx lname lurl src copyleft dist note; do
  [[ -z "$var" || "$var" == \#* ]] && continue
  [[ -n "$note" ]] || die "row $var: expected 9 TAB-separated columns"
  ver="${!var}"
  [[ -n "$ver" ]] || die "$var is empty in versions.env"
  base="${var%_VERSION}"
  if [[ "$src" == "@" ]]; then
    urlvar="${base}_URL"
    src="${!urlvar:-}"
    [[ -n "$src" ]] || die "$urlvar missing in versions.env (row $var uses @)"
  fi
  ver_="${ver//./_}"
  src="${src//\{version_\}/$ver_}"; src="${src//\{version\}/$ver}"
  lurl="${lurl//\{version_\}/$ver_}"; lurl="${lurl//\{version\}/$ver}"
  case "$copyleft" in yes|no) ;; *) die "row $var: copyleft must be yes|no";; esac
  case "$dist" in bundled|downloaded) ;; *) die "row $var: distribution must be bundled|downloaded";; esac
  [[ "$note" == "-" ]] && note=""
  rows+=("$var"$'\t'"$name"$'\t'"$ver"$'\t'"$spdx"$'\t'"$lname"$'\t'"$lurl"$'\t'"$src"$'\t'"$copyleft"$'\t'"$dist"$'\t'"$note")
done <"$tsv"

anchor() { printf '%s' "$1" | tr '[:upper:]' '[:lower:]' | tr '_' '-'; }

render_release_notes() {
  echo "### Third-party licenses"
  echo
  echo "RAMP (MIT) installs the following separately licensed programs (aggregation). Full list: THIRD_PARTY_LICENSES.md."
  echo "Source code for copyleft components (exact pinned versions):"
  echo
  for r in "${rows[@]}"; do
    IFS=$'\t' read -r var name ver spdx lname lurl src copyleft dist note <<<"$r"
    [[ "$copyleft" == yes ]] || continue
    echo "- $name $ver ($spdx): $src"
  done
}

render_file() {
  echo "# Third-party licenses"
  echo
  echo "<!-- GENERATED by build/third-party-licenses.sh from build/versions.env + build/licenses/components.tsv. Do not edit by hand. -->"
  echo
  echo "RAMP itself is licensed under the MIT License (see [LICENSE](LICENSE))."
  echo
  echo "RAMP downloads and runs the programs below as separate, independent programs (mere aggregation);"
  echo "their licenses do not extend to RAMP and RAMP's license does not extend to them. Each component"
  echo "keeps its own license, reproduced in full inside its source tarball. Versions are the exact pins"
  echo "from \`build/versions.env\`. For copyleft components the corresponding source code is available at"
  echo "the linked version tag / source tarball."
  echo
  echo "| Component | Version | License (SPDX) | Distribution |"
  echo "|---|---|---|---|"
  for r in "${rows[@]}"; do
    IFS=$'\t' read -r var name ver spdx lname lurl src copyleft dist note <<<"$r"
    echo "| [$name](#$(anchor "$var")) | $ver | \`$spdx\` | $dist |"
  done
  echo
  echo "System libraries (zlib, libiconv, bzip2, libedit, libc++) are provided by macOS and are not distributed."
  echo
  echo "## Components"
  for r in "${rows[@]}"; do
    IFS=$'\t' read -r var name ver spdx lname lurl src copyleft dist note <<<"$r"
    echo
    echo "<a id=\"$(anchor "$var")\"></a>"
    echo "### $name $ver"
    echo
    echo "- License: [$lname]($lurl) (\`$spdx\`)"
    if [[ "$copyleft" == yes ]]; then
      echo "- Source code: <$src>"
    else
      echo "- Source: <$src>"
    fi
    if [[ "$dist" == downloaded ]]; then
      echo "- Distribution: downloaded from upstream at the user's request, not redistributed by RAMP"
    fi
    [[ -z "$note" ]] || echo "- Note: $note"
  done
}

case "$mode" in
  write)
    tmp="$(mktemp)"; trap 'rm -f "$tmp"' EXIT
    render_file >"$tmp"
    mv "$tmp" "$out"; trap - EXIT
    chmod 0644 "$out"
    echo "wrote $out (${#rows[@]} components)" ;;
  --check)
    diff -u "$out" <(render_file) >/dev/null || die "$out is stale — run build/third-party-licenses.sh"
    echo "ok: $out up to date (${#rows[@]} components)" ;;
  --release-notes) render_release_notes ;;
  *) die "usage: $0 [--check|--release-notes]" ;;
esac
